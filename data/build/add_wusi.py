def main():
    out_data = json.load(open(DST))
    cid = 'H_H2_CM_07'

    # 删原 _001-_005 (如果有, 即使是 V4.0.0 老题也覆盖)
    prefix = f"EX_{cid}_"
    out_data['exercises'] = [e for e in out_data['exercises'] if not e['id'].startswith(prefix)]

    # 写新 5 道
    for i, ex in enumerate(EXERCISES):
        ex_id = f"EX_{cid}_{i+1:03d}"
        item = {
            'id': ex_id,
            'concept_id': cid,
            'type': ex['type'],
            'difficulty': 3,
            'question': ex['question'],
            'answer': ex['answer'],
            'explanation': ex['explanation'],
            'bloom': '理解' if ex['type'] == 'multiple_choice' else '记忆' if ex['type'] == 'fill_blank' else '分析',
            'is_real_exam': False,
            'tags': ['手动入库', '敏感词概念'],
        }
        if ex['type'] == 'multiple_choice':
            item['options'] = ex['options']
        out_data['exercises'].append(item)

    with open(DST, 'w', encoding='utf-8') as f:
        json.dump(out_data, f, ensure_ascii=False, indent=2)
    print(f'✅ 5 道题入库, 总 {len(out_data["exercises"])} 题')


if __name__ == '__main__':
    main()
