def main():
    out_data = json.load(open(DST))
    print(f'开始前: {len(out_data["exercises"])} 题')

    n_added = 0
    for cid, info in MANUAL.items():
        # 删原 _001-_005 (如果有)
        prefix = f"EX_{cid}_"
        before = len(out_data['exercises'])
        out_data['exercises'] = [e for e in out_data['exercises'] if not e['id'].startswith(prefix)]
        deleted = before - len(out_data['exercises'])
        if deleted:
            print(f'  🗑  {cid}: 删 {deleted} 道旧题')

        for i, ex in enumerate(info['exercises']):
            ex_id = f"EX_{cid}_{i+1:03d}"
            item = {
                'id': ex_id,
                'concept_id': cid,
                'type': ex['type'],
                'difficulty': 3,
                'question': ex['question'],
                'answer': ex['answer'],
                'explanation': ex['explanation'],
                'bloom': '理解' if ex['type'] == 'multiple_choice' else '记忆' if ex['type'] == 'fill_blank' else '分析',
                'is_real_exam': False,
                'tags': ['手动入库', 'LLM失败概念'],
            }
            if ex['type'] == 'multiple_choice':
                item['options'] = ex['options']
            out_data['exercises'].append(item)
            n_added += 1
        print(f'  ✅ {cid} ({info["title"]}): 补 5 道题')

    with open(DST, 'w', encoding='utf-8') as f:
        json.dump(out_data, f, ensure_ascii=False, indent=2)
    print(f'\n✅ 新增 {n_added} 道题, 总 {len(out_data["exercises"])} 题')


if __name__ == '__main__':
    main()
