    # 应用 FIX 补丁
    for idx, (d, a) in FIX.items():
        cur_d, cur_a = ENTRIES[idx - 1]
        if d is not None:
            cur_d = d
        if a is not None:
            cur_a = a
        ENTRIES[idx - 1] = (cur_d, cur_a)

    out = []
    total_desc_len = 0
    total_ass_len = 0
    rewrite_count = 0
    banned_total = 0
    fails = []
    for i, item in enumerate(inp):
        desc, ass = ENTRIES[i]
        merged = {**item, "description": desc, "assessment_prompt": ass}
        out.append(merged)

        dlen = len(desc)
        alen = len(ass)
        ncount = ass.count("{{name}}")
        nlcount = ass.count(chr(10))  # 真实换行符
        bd = has_banned(desc)
        ba = has_banned(ass)
        ok = True
        reasons = []
        if not (60 <= dlen <= 100):
            reasons.append(f"desc_len={dlen}")
            ok = False
        if not (150 <= alen <= 220):
            reasons.append(f"ass_len={alen}")
            ok = False
        if ncount != 3:
            reasons.append(f"name={ncount}")
            ok = False
        if nlcount < 2:
            reasons.append(f"newline={nlcount}")
            ok = False
        if bd or ba:
            reasons.append(f"banned_desc={bd} banned_ass={ba}")
            ok = False
        total_desc_len += dlen
        total_ass_len += alen
        banned_total += len(bd) + len(ba)
        if not ok:
            fails.append((i+1, item["id"], item["title"], reasons))
            rewrite_count += 1

