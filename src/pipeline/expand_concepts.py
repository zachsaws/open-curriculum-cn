def expand_subject(subject, existing_titles, ocr_data, target_count=None):
    """
    对一个学科扩 concept
    1. 用 PRESEED 加
    2. 用 OCR 启发式加 (可选)
    3. 编号生成 ID
    """
    preseed = SUBJECT_PRESEED.get(subject, {})
    new_concepts = []

    for stage, domains in preseed.items():
        for domain, subdomains in domains.items():
            idx = 0
            for subdomain, items in subdomains.items():
                for title, summary, difficulty in items:
                    if is_duplicate(title, existing_titles):
                        continue
                    # 找到 content_req: 用 PRESEED summary + 加上学段描述
                    content_req = f'在{stage_name_cn(stage)}教学情境中,{summary}。'
                    concept = make_concept(
                        subject, stage, domain, subdomain, title, summary, content_req, difficulty
                    )
                    new_concepts.append(concept)
                    existing_titles.add(normalize_title(title))
                    idx += 1
    return new_concepts


