def assign_ids(concepts):
    """按 (_sub_marker) 分组, 给每个新概念编 NN 编号
    ID 续 V0.7 已有最高编号, 避免冲突
    """
    # 找每个 (sub_marker) 的最大现存编号
    # 用 V0.7 的最高编号 + 1
    from collections import defaultdict
    by_marker = defaultdict(int)
    for c in concepts:
        if '_sub_marker' in c:
            by_marker[c['_sub_marker']] += 1
    return by_marker


def renumber_concepts(concepts, base_data, subject):
    """对所有新概念按 (stage, domain) 重新编号, 从 V0.7 已有 max+1 开始"""
    from collections import defaultdict
    # 找 V0.7 中各 (stage, domain) 已有 max 编号
    code = SUBJECT_CODE[subject]
    max_idx = defaultdict(int)
    for n in base_data['nodes']:
        sid = n['id']
        # 解析: {code}_{g}_{d}_{nn}
        # 提取 (g_marker, d_code) 和 idx
        m = re.match(rf'^{code}_([G\d]{{1,3}})([A-Z]{{2}})_(\d+)$', sid)
        if m:
            g = m.group(1)
            d = m.group(2)
            idx = int(m.group(3))
            key = f'{g}_{d}'
            if idx > max_idx[key]:
                max_idx[key] = idx
    # 给新概念编 ID
    for c in concepts:
        if '_sub_marker' in c:
            sm = c['_sub_marker']
            max_idx[sm] += 1
            c['id'] = f'{code}_{sm}_{max_idx[sm]:02d}'
        del c['_placeholder_id']
        del c['_sub_marker']


