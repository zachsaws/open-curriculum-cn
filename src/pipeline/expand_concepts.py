def stage_to_grade(stage):
    """stage(1/2/3/4) → (grade_start, grade_end)"""
    return {1: (1, 2), 2: (3, 4), 3: (5, 6), 4: (7, 9)}.get(stage, (1, 2))


def extract_bloom(text):
    found = []
    for v in BLOOM_VERBS:
        if v in text and v not in found:
            found.append(v)
        if len(found) >= 3:
            break
    return found if found else ["了解"]


def extract_key_points(text, max_n=5):
    sents = re.split(r'[，。;；,]+', text)
    sents = [s.strip() for s in sents if 6 <= len(s.strip()) <= 40]
    scored = []
    for s in sents:
        v_score = sum(1 for v in BLOOM_VERBS if v in s)
        scored.append((v_score, s))
    scored.sort(key=lambda x: -x[0])
    out = []
    for _, s in scored:
        if s not in out and len(out) < max_n:
            out.append(s)
    return out[:max_n] if out else [text[:30] + "..."]


def estimate_minutes(difficulty):
    return {1: 15, 2: 25, 3: 40, 4: 60, 5: 90}.get(difficulty, 30)


def normalize_title(t):
    """模糊匹配用: 去掉 (括号)/空格/中文标点, 取 8 字"""
    if not t:
        return ''
    t = re.sub(r'[\s（）()【】《》、,。.!?;；:：·\-+/\\]', '', t)
    return t[:8]


def is_duplicate(title, existing_titles):
    """模糊判断 title 是否已在 existing_titles"""
    n = normalize_title(title)
    if not n or len(n) < 2:
        return True
    for ex in existing_titles:
        ex_n = normalize_title(ex)
        if ex_n == n:
            return True
        # 子串匹配
        if len(n) >= 4 and (n in ex_n or ex_n in n):
            return True
        # 重叠 70%
        common = sum(1 for c in n if c in ex_n)
        if common >= len(n) * 0.7 and len(n) >= 4:
            return True
    return False


def load_base(subjects):
    """加载 V0.8.bak = V0.7 现状作为基础"""
    base = {}
    for s in subjects:
        bak = GRAPH_DIR / f"{s}_v0.8.json.bak"
        if not bak.exists():
            # fallback to v0.7
            bak = GRAPH_DIR / f"{s}_v0.7.json"
        with open(bak) as f:
            d = json.load(f)
        base[s] = d
    return base


