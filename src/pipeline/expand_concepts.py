def deep_merge(target, source):
    """递归合并: source 的 key/value 合并到 target, 不覆盖 target 已有 key 的子字典"""
    for k, v in source.items():
        if k in target and isinstance(target[k], dict) and isinstance(v, dict):
            deep_merge(target[k], v)
        else:
            target[k] = v


