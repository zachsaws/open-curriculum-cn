def build():
    subject = "math"
    nodes = []
    for cid, title, g_start, g_end, domain, subdomain, difficulty, summary in PRESEED_CONCEPTS:
        nodes.append({
            "id": cid,
            "subject": subject,
            "stage": (g_start + g_end) // 2 // 2 + 1,  # 1-2/3-4/5-6/7-9 → 1/2/3/4
            "grade_start": g_start,
            "grade_end": g_end,
            "title": title,
            "domain": domain,
            "subdomain": subdomain,
            "difficulty": difficulty,
            "summary": summary,
            "source": "2022 义教数学课标 OCR",
        })
    # 验证节点
    ids = {n["id"] for n in nodes}
    edges = []
    for fr, to, typ in PREREQ_EDGES:
        if fr not in ids:
            print(f"WARN: missing from-node {fr}")
            continue
        if to not in ids:
            print(f"WARN: missing to-node {to}")
            continue
        if fr == to:
            print(f"WARN: self-loop {fr}")
            continue
        edges.append({"from": fr, "to": to, "type": typ})
    print(f"math v0.6: {len(nodes)} concepts, {len(edges)} edges")
    return {"nodes": nodes, "edges": edges}


